// The event site uses Boxicons. Keep filled icons consistent across the portal.
type Props = Omit<BoxIconProps, "pack">;
const filled = (Icon: React.ComponentType<BoxIconProps>) => {
  function FilledIcon(props: Props) {
    return <Icon {...props} pack="filled" />;
  }
  FilledIcon.displayName = `Filled${Icon.displayName ?? Icon.name}`;
  return FilledIcon;
};

